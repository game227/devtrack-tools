import puppeteer from 'puppeteer-core'
const [OUT, route, selector, name, openDetails] = process.argv.slice(2)
const browser = await puppeteer.launch({ executablePath: '/snap/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-gpu', '--hide-scrollbars'] })
const page = await browser.newPage()
page.setDefaultNavigationTimeout(90000)
await page.setViewport({ width: 1100, height: 900 })
await page.evaluateOnNewDocument(() => { localStorage.setItem('devtrack_lang', 'uz'); localStorage.setItem('devtrack_workspace', '6') })
await page.goto('http://localhost:5173/login', { waitUntil: 'networkidle0' })
await page.type('input[autocomplete="username"]', 'jane.dev')
await page.type('input[autocomplete="current-password"]', 'demo1234')
await Promise.all([page.waitForNavigation({ waitUntil: 'networkidle0' }), page.click('button[type="submit"]')])
await page.goto(`http://localhost:5173${route}`, { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 800))
if (openDetails) await page.evaluate(() => document.querySelector('details')?.setAttribute('open', ''))
const el = await page.evaluateHandle((sel) => document.querySelector(sel)?.closest('div.rounded-2xl') ?? document.querySelector(sel), selector)
await el.asElement().screenshot({ path: `${OUT}/${name}.png` })
await browser.close(); console.log('ok')
